CREATE OR REPLACE PROCEDURE P_MODIFIER_LE_NOMBRE_DE_TRAVAILLEUR_PAR(
    P_ID_CHANTIER CHANTIERS.ID_CHANTIER%TYPE,
    P_NOUVEAU_NOMBRE_DE_TRAVAILLEUR CHANTIERS.NOMBRE_TRAVAILLEUR%TYPE
) AS

BEGIN
    IF P_NOUVEAU_NOMBRE_DE_TRAVAILLEUR < 0 OR P_NOUVEAU_NOMBRE_DE_TRAVAILLEUR > 100 THEN
        DBMS_OUTPUT.PUT_LINE('LE NOMBRE DE TRAVAILLEUR DOIT ETRE COMPRIS ENTRE 0 ET 100 MAXIMUM');
    ELSE
        UPDATE CHANTIERS SET NOMBRE_TRAVAILLEUR = P_NOUVEAU_NOMBRE_DE_TRAVAILLEUR 
        WHERE ID_CHANTIER = P_ID_CHANTIER;

        DBMS_OUTPUT.PUT_LINE('MODIFICATION EFFECTUEE AVEC SUCCES');
    END IF;
END;
