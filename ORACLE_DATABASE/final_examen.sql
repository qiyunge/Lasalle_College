-- question 11
CREATE OR REPLACE TRIGGER T_UPDATE_STATS_CHANTIERS
AFTER INSERT OR UPDATE OR DELETE ON CHANTIERS
FOR EACH ROW
DECLARE
BEGIN
    IF INSERTING THEN

        INSERT INTO STATS_CHANTIERS (COUNT_CHANTIER, ID_CHANTIER) VALUES (:NEW.NOMBRE_TRAVAILLEUR * :NEW.TARIF_TRAVAILLEUR, :NEW.ID_CHANTIER);
    ELSIF UPDATING THEN
        UPDATE STATS_CHANTIERS SET COUNT_CHANTIER = :NEW.NOMBRE_TRAVAILLEUR * :NEW.TARIF_TRAVAILLEUR WHERE ID_CHANTIER = :NEW.ID_CHANTIER;
    ELSIF DELETING THEN
        DELETE FROM STATS_CHANTIERS WHERE ID_CHANTIER = :OLD.ID_CHANTIER;
    END IF;
END;

/


