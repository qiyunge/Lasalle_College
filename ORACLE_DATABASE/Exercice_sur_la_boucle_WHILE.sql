DECLARE
    V_COUNT_EMPLOES_INF3000 INT := 0;

BEGIN
    SELECT COUNT(*) INTO V_COUNT_EMPLOES_INF3000 FROM EMPLOYES WHERE SALAIRE < 3000;
    WHILE V_COUNT_EMPLOES_INF3000 > 0 LOOP
        DBMS_OUTPUT.PUT_LINE('Nombre d''employes avec un salaire inferieur a 3000: ' || V_COUNT_EMPLOES_INF3000);
        UPDATE EMPLOYES SET SALAIRE = SALAIRE + 200;
        SELECT COUNT(*) INTO V_COUNT_EMPLOES_INF3000 FROM EMPLOYES WHERE SALAIRE < 3000;
    END LOOP;
    COMMIT;
END;
