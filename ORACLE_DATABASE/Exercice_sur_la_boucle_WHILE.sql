DECLARE
    V_SALAIRE_MOYEN EMPLOYES.SALAIRE%TYPE;
    C_DEPARTEMENT CONSTANT EMPLOYES.DEPARTEMENT%TYPE := 'IT';  
BEGIN
    SELECT AVG(SALAIRE) INTO V_SALAIRE_MOYEN FROM EMPLOYES WHERE DEPARTEMENT = C_DEPARTEMENT;
    WHILE V_SALAIRE_MOYEN <7000 LOOP
     
        UPDATE EMPLOYES SET SALAIRE = SALAIRE * 1.05 WHERE DEPARTEMENT = C_DEPARTEMENT;
        SELECT AVG(SALAIRE) INTO V_SALAIRE_MOYEN FROM EMPLOYES WHERE DEPARTEMENT = C_DEPARTEMENT;
        DBMS_OUTPUT.PUT_LINE('Salaire moyen dans le departement ' || C_DEPARTEMENT || ' est de: ' || V_SALAIRE_MOYEN);
    END LOOP;
    COMMIT;
END;
