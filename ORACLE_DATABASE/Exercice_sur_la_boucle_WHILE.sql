    WHILE V_ID <= V_ID_MAX LOOP
        IF MOD(V_ID,2) != 0 THEN
            UPDATE EMPLOYES SET SALAIRE = SALAIRE + 100 WHERE ID_EMP = V_ID;
            DBMS_OUTPUT.PUT_LINE('Employe ID: ' || V_ID || ' - Salaire mis a jour de 100 pour ID pair.');
