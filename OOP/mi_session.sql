CREATE OR REPLACE FUNCTION LE_PRIX_LE_PLUS_GRAND_DE(P_CATEGORIE PRODUITS.CATEGORIE%TYPE)
RETURN PRODUITS.PRIX%TYPE IS
    V_PRIX_MAX PRODUITS.PRIX%TYPE;

BEGIN
    SELECT MAX(PRIX) INTO V_PRIX_MAX FROM PRODUITS
    WHERE CATEGORIE = P_CATEGORIE;
    RETURN V_PRIX_MAX;
END;

