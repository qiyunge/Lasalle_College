CREATE OR REPLACE PROCEDURE MODIFIER_PRIX_DE (P_ID_PRODUIT PRODUITS.ID_PRODUIT%TYPE,
P_NOUVEAU_PRIX PRODUITS.PRIX%TYPE) IS
    V_PRIX_MAX PRODUITS.PRIX%TYPE := 8000;
BEGIN
    IF P_NOUVEAU_PRIX <= V_PRIX_MAX THEN
        UPDATE PRODUITS SET PRIX = P_NOUVEAU_PRIX
        WHERE ID_PRODUIT = P_ID_PRODUIT;
    ELSE 
        DBMS_OUTPUT.PUT_LINE('LE NOUVEAU PRIX NE PEUT PAS DEPASSER LE PRIX MAXIMUM AUTORISE QUI EST DE 8000$');
    END IF;
END;

