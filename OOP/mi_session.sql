CREATE OR REPLACE FUNCTION LE_NOM_DE_LE_PLUS_GRAND_PRIX_DE(P_CATEGORIE PRODUITS.CATEGORIE%TYPE) 
RETURN PRODUITS.NOM%TYPE     IS
    V_NOM_PRODUIT PRODUITS.NOM%TYPE;
    V_CAT_PRODUIT PRODUITS.CATEGORIE%TYPE;
BEGIN
    SELECT NOM,CATERGORIE  FROM
    (SELECT NOM,CATERGORIE INTO V_NOM_PRODUIT,V_CAT_PRODUIT FROM PRODUITS WHERE CATEGORIE = P_CATEGORIE ORDER BY PRIX DESC) T WHERE ROWNUM = 1;
    IF V_CAT_PRODUIT = 'FILM' OR V_CAT_PRODUIT = 'ANIME' THEN
        RETURN V_NOM_PRODUIT;
    ELSE 
        DBMS_OUTPUT.PUT_LINE('Aucun produit trouvé dans la catégorie spécifiée');
    END IF;
END;


